def _run_noise_report(inputs: dict) -> int:
    rows = inputs.get("after")
    if rows is None:
        print(f"ERROR: {inputs.get('after_path')} not found", file=sys.stderr)
        return 1
    bad = False
    for op in CROSSLANG_OPS:
        source = f"criterion:crosslang_{op}/n500_m200"
        row = next((r for r in rows if r.get("source") == source), None)
        if row is None:
            print(f"NOISE {source} rsd=nan ciw=nan MISSING")
            bad = True
            continue
        rsd = _safe_float(row.get("rsd_pct"))
        ciw = _safe_float(row.get("ci_width_pct"))
        status = noise_status(row)
        rsd_str = f"{rsd:.2f}" if rsd is not None else "nan"
        ciw_str = f"{ciw:.2f}" if ciw is not None else "nan"
        print(f"NOISE {source} rsd={rsd_str} ciw={ciw_str} {status}")
        if status != "PASS":
            bad = True
    return 1 if bad else 0


def _run_ab_check(inputs: dict) -> int:
    manifest = inputs.get("ab_manifest")
    if manifest is None:
        print(f"ERROR: {inputs.get('ab_manifest_path')} not found", file=sys.stderr)
        return 1
    for entry in manifest.get("entries", []):
        if entry.get("kind") != "ab":
            print(f"AB {entry.get('id')} kind={entry.get('kind')} (no before/after pair)")
            continue
        stats = _ab_stats_for(inputs, entry)
        print(
            f"AB {entry.get('id')} speedup={stats['speedup']:.3f} delta_pct={stats['delta_pct']:.2f} "
            f"significant={stats['significant']} "
            f"noise={stats['before']['noise_gate']}/{stats['after']['noise_gate']} "
            f"headline_eligible={stats['headline_eligible']}"
        )

    headline = select_headline_ab(manifest)
    if headline is None:
        print("AB-CHECK: no headline entry found")
        return 1
    stats = _ab_stats_for(inputs, headline)
    if stats["headline_eligible"]:
        print(f"AB-CHECK: PASS ({headline['id']} eligible)")
        return 0
    print(f"AB-CHECK: FAIL ({headline['id']} not eligible)")
    return 1


