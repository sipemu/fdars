def _flatten(d: dict, prefix: str = "") -> list[tuple[str, object]]:
    items: list[tuple[str, object]] = []
    for key, value in d.items():
        full_key = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            items.extend(_flatten(value, full_key))
        else:
            items.append((full_key, value))
    return items


def emit_environment(inputs: dict) -> str:
    env = inputs.get("env") or {}
    env_baseline = inputs.get("env_baseline") or {}
    baseline_flat = dict(_flatten(env_baseline))
    after_flat = dict(_flatten(env))
    keys = sorted(set(baseline_flat) | set(after_flat))

    lines = [
        _notice(["env.json", "env_baseline.json"]),
        "",
        "| Item | Phase 113 baseline | Phase 116 re-run | Changed? |",
        "|---|---|---|---|",
    ]
    for key in keys:
        before_value = baseline_flat.get(key)
        after_value = after_flat.get(key)
        changed = "yes" if before_value != after_value else "no"
        lines.append(f"| {key} | {_md_cell(before_value)} | {_md_cell(after_value)} | {changed} |")
    return "\n".join(lines)


