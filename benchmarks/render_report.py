def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Render generated performance tables into a markdown doc "
                     "from committed cross-language comparison CSVs."
    )
    parser.add_argument("--baseline", type=str, default="benchmarks/results/comparison_baseline.csv")
    parser.add_argument("--after", type=str, default="benchmarks/results/comparison.csv")
    parser.add_argument("--env", type=str, default="benchmarks/results/env.json")
    parser.add_argument("--env-baseline", type=str, default="benchmarks/results/env_baseline.json")
    parser.add_argument("--rerun-log", type=str, default="benchmarks/results/rerun_log.json")
    parser.add_argument("--ab-manifest", type=str, default="benchmarks/results/ab/manifest.json")
    parser.add_argument("--doc", type=str, default="documentation/PERFORMANCE.md")
    parser.add_argument("--readme", type=str, default="README.md")
    parser.add_argument("--bench-dir", type=str, default="fdars-core/benches")
    parser.add_argument(
        "--blocks", type=str, nargs="+", default=list(BLOCKS),
        help=f"Which generated blocks to render (default: all of {list(BLOCKS)}).",
    )
    parser.add_argument("--check", action="store_true", help="Fail if any doc is stale; never writes.")
    parser.add_argument("--noise-report", action="store_true", help="Print per-op headline noise status.")
    parser.add_argument("--ab-check", action="store_true", help="Print A/B stats; exit 0 iff headline-eligible.")
    parser.add_argument(
        "--check-prose", action="store_true",
        help="Fail if hand-written prose quotes a number not backed by a generated block.",
    )
    args = parser.parse_args(argv)

    unknown_blocks = [b for b in args.blocks if b not in BLOCKS]
    if unknown_blocks:
        print(f"ERROR: unknown block(s) {unknown_blocks}; valid blocks: {list(BLOCKS)}", file=sys.stderr)
        return 2

    if args.check_prose:
        doc_path = pathlib.Path(args.doc)
        readme_path = pathlib.Path(args.readme)
        if not doc_path.exists():
            print(f"ERROR: {doc_path} not found", file=sys.stderr)
            return 1
        doc_text = doc_path.read_text(encoding="utf-8")
        readme_text = readme_path.read_text(encoding="utf-8") if readme_path.exists() else ""
        offenders = check_prose(doc_text, readme_text)
        if offenders:
            print("ERROR: prose numbers not backed by a generated block:", file=sys.stderr)
            for offender in offenders:
                print(f"  {offender}", file=sys.stderr)
            return 1
        print("check-prose OK")
        return 0

    inputs = _load_inputs(args)

    if args.noise_report:
        return _run_noise_report(inputs)
    if args.ab_check:
        return _run_ab_check(inputs)

    try:
        rendered = render_blocks(inputs, args.blocks)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    doc_paths = [p for p in (args.doc, args.readme) if pathlib.Path(p).exists()]
    if not doc_paths:
        print(f"ERROR: no doc found among {args.doc}, {args.readme}", file=sys.stderr)
        return 1

    try:
        stale = update_docs(doc_paths, rendered, write=not args.check)
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if stale:
            print(f"STALE: {stale}")
            return 1
        print("check OK — all blocks up to date")
        return 0

    print(f"Rendered block(s) {list(rendered)} into {doc_paths}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
