def emit_headline(rows: list[dict], ops: list[str], cell: tuple[int, int]) -> str:
    """
    Emit the headline markdown table: one row per op at a single (N, M) cell.

    A trailing dagger marks an fdars value whose noise_gate is not PASS
    (measurement failed the RSD/CI-width noise gate — never headlined as a
    confirmed win/loss, per D-06/D-08).
    """
    n, m = cell
    lines: list[str] = [_notice(["comparison.csv"]), "", _HEADLINE_HEADER, _HEADLINE_SEPARATOR]

    for op in ops:
        sel = select_cell(rows, op, n, m)
        fdars_row = sel["fdars"]
        python_row = sel["python"]
        r_row = sel["r"]

        fdars_ns = fdars_row.get("mean_ns") if fdars_row else None
        python_ns = python_row.get("mean_ns") if python_row else None
        r_ns = r_row.get("mean_ns") if r_row else None

        fdars_ms = _ms(float(fdars_ns)) if fdars_ns is not None else _EM_DASH
        if fdars_row is not None and fdars_row.get("noise_gate") != "PASS":
            fdars_ms = f"{fdars_ms}{_NOISE_DAGGER}"
        python_ms = _ms(float(python_ns)) if python_ns is not None else _EM_DASH
        r_ms = _ms(float(r_ns)) if r_ns is not None else _EM_DASH

        vs_python = ratio_label(fdars_ns, python_ns)
        vs_r = ratio_label(fdars_ns, r_ns)

        lines.append(f"| {op} | {n} | {m} | {fdars_ms} | {python_ms} | {r_ms} | {vs_python} | {vs_r} |")

    lines.append("")
    lines.append(
        f"{_NOISE_DAGGER} fdars measurement failed the noise gate "
        "(RSD >= 5% or CI-width >= 5%) — not headlined as significant."
    )
    return "\n".join(lines)


