def load_rows(path: str | pathlib.Path) -> list[dict]:
    """
    Load a comparison-schema CSV into a list of row dicts (NaN -> None).

    Uses `keep_default_na=False, na_values=[""]` because pandas' default NA
    sniffing parses the literal string "NA" (python/r's noise_gate value) as
    NaN, which `rank_hotspots.apply_noise_gate` would then treat as an
    unknown/unparseable noise_gate and conservatively exclude — silently
    breaking the NA-means-cross-language-row convention. Only truly empty
    fields become NaN (-> None after `_df_to_rows`).
    """
    df = pd.read_csv(path, keep_default_na=False, na_values=[""])
    rows = _df_to_rows(df)
    # pandas re-casts `.where(..., None)` back to NaN on float64 columns
    # (dtype-preserving `.where`, observed on pandas >= 3.0) — normalize any
    # remaining NaN to a real `None` so every downstream consumer sees one
    # consistent "missing" sentinel rather than two (None vs float("nan")).
    for row in rows:
        for key, value in row.items():
            if isinstance(value, float) and value != value:
                row[key] = None
    return rows


def _safe_float(value) -> float | None:
    """Best-effort float conversion; None/NaN/unparsable -> None."""
    try:
        f = float(value)
    except (TypeError, ValueError):
        return None
    if f != f:  # NaN
        return None
    return f


def _to_int(value) -> int | None:
    f = _safe_float(value)
    return None if f is None else int(f)


def _num_eq(a, b) -> bool:
    fa, fb = _safe_float(a), _safe_float(b)
    return fa is not None and fb is not None and fa == fb


def _cell_matches(row: dict, n: int, m: int) -> bool:
    """True if row['n']/row['m'] parse to the given (n, m) (NaN-safe)."""
    try:
        return int(row.get("n")) == n and int(row.get("m")) == m
    except (TypeError, ValueError):
        return False


def select_cell(rows: list[dict], op: str, n: int, m: int) -> dict:
    """
    Select the fdars / python / r rows for one (op, n, m) headline cell.

    - "fdars": the row whose `source` equals `criterion:crosslang_{op}/n{n}_m{m}`
      — the grid-aligned fdars bench (fdars-core/benches/crosslang_grid.rs),
      NOT the pre-existing non-grid-aligned criterion ids.
    - "python": the `library == "python"` row with matching op/n/m.
    - "r": the `library == "r_svd"` row with matching op/n/m (the SVD-matched
      R FPCA comparator, not the ecosystem-realistic `r_native_pca_fd`; see
      116-CONTEXT.md).

    Any of the three may be missing (value is None) — callers render a missing
    value as an em dash and never headline an incomplete row.
    """
    fdars_source = f"criterion:crosslang_{op}/n{n}_m{m}"
    fdars_row = next((r for r in rows if r.get("source") == fdars_source), None)
    python_row = next(
        (
            r
            for r in rows
            if r.get("library") == "python" and r.get("op") == op and _cell_matches(r, n, m)
        ),
        None,
    )
    r_row = next(
        (
            r
            for r in rows
            if r.get("library") == "r_svd" and r.get("op") == op and _cell_matches(r, n, m)
        ),
        None,
    )
    return {"fdars": fdars_row, "python": python_row, "r": r_row}


