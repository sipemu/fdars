def ratio_label(fdars_ns, other_ns, band_pct: float = _PARITY_BAND_PCT) -> str:
    """
    Label the fdars-vs-other speed relationship for one headline cell.

    ratio = other_ns / fdars_ns.
      - ratio >= 1 + band/100        -> "{ratio:.2f}x faster" (fdars is faster)
      - ratio <= 1 / (1 + band/100)  -> "{fdars/other:.2f}x slower" (fdars is slower)
      - otherwise                    -> "comparable" (within the parity band)
    A missing/non-numeric/non-positive input returns an em dash.
    """
    try:
        fdars_f = float(fdars_ns)
        other_f = float(other_ns)
    except (TypeError, ValueError):
        return _EM_DASH
    if fdars_f != fdars_f or other_f != other_f:  # NaN check (NaN != NaN)
        return _EM_DASH
    if fdars_f <= 0 or other_f <= 0:
        return _EM_DASH

    band = band_pct / 100.0
    ratio = other_f / fdars_f
    if ratio >= 1.0 + band:
        return f"{ratio:.2f}{_TIMES} faster"
    if ratio <= 1.0 / (1.0 + band):
        return f"{(fdars_f / other_f):.2f}{_TIMES} slower"
    return "comparable"


