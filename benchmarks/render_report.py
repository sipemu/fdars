"""
render_report.py — Generated-table renderer for the fdars Phase 116 perf report.

Inputs: benchmarks/results/comparison.csv (after-run) and, in later plans,
benchmarks/results/comparison_baseline.csv (Phase 113 before-run) plus
benchmarks/results/env.json (methodology disclosure). This tracer plan
(116-01) wires only the `--after` CSV and the `headline` block; 116-04 adds
the before/after, scaling, and methodology blocks on this same scaffold.

Outputs: generated markdown blocks spliced into documentation/PERFORMANCE.md
(and, in a later plan, a short headline snippet for README.md) between
`<!-- BEGIN GENERATED: <name> -->` / `<!-- END GENERATED: <name> -->` marker
pairs. Tables are GENERATED by this script from the committed CSVs; the
surrounding prose is hand-written and never touched by splice_generated.

Usage:
    python render_report.py --after benchmarks/results/comparison.csv \\
        --doc documentation/PERFORMANCE.md --blocks headline
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import pandas as pd

# Same-directory module import, late (after stdlib + third-party imports),
# matching the benchmarks/test_rank_hotspots.py idiom.
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from rank_hotspots import _df_to_rows, _ms  # noqa: E402  (module in same directory)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# The six ops the cross-language harness times (benchmarks/run_all.py::ALL_OPS).
CROSSLANG_OPS = ("fpca", "basis_smoothing", "depth", "functional_boxplot", "fpcr", "elastic")

# Locked N×M grid (benchmarks/run_all.py::GRID_N / GRID_M).
GRID_N = (100, 300, 500)
GRID_M = (50, 200)

# The largest grid cell — the report's headline comparison point.
HEADLINE_CELL = (500, 200)

# Parity band for ratio_label: within +/- this percent, fdars and the
# competitor are reported as "comparable" rather than faster/slower.
_PARITY_BAND_PCT = 10.0

# Generated blocks this script knows how to render. main() fails closed (exit
# 2) on any --blocks name not in this tuple.
BLOCKS = ("headline",)

_HEADLINE_HEADER = (
    "| Op | N | M | fdars (ms) | scikit-fda (ms) | R (ms) | fdars vs scikit-fda | fdars vs R |"
)
_HEADLINE_SEPARATOR = (
    "|----|---|---|------------|------------------|--------|----------------------|------------|"
)
_NOISE_DAGGER = "†"
_EM_DASH = "—"
_TIMES = "×"


# ---------------------------------------------------------------------------
# Generated-block splicing (shared by every block this script emits)
# ---------------------------------------------------------------------------


def block_markers(name: str) -> tuple[str, str]:
    """Return the (BEGIN, END) marker line pair for a generated block `name`."""
    return (f"<!-- BEGIN GENERATED: {name} -->", f"<!-- END GENERATED: {name} -->")


def splice_generated(text: str, name: str, content: str) -> str:
    """
    Replace everything strictly between the BEGIN/END GENERATED marker lines
    for `name` with `content`.

    Raises ValueError if either marker is missing from `text`, or if either
    marker line appears more than once (an ambiguous splice target — the doc
    must carry exactly one marker pair per block name).

    Idempotent: splicing identical `content` into an already-spliced document
    returns the document byte-for-byte unchanged, which is what the plan's
    "re-running step 6(e) leaves `git diff --quiet` true" determinism
    requirement relies on.
    """
    begin_marker, end_marker = block_markers(name)
    lines = text.splitlines(keepends=True)

    begin_indices = [i for i, line in enumerate(lines) if line.rstrip("\n") == begin_marker]
    end_indices = [i for i, line in enumerate(lines) if line.rstrip("\n") == end_marker]

    if not begin_indices:
        raise ValueError(f"splice_generated: BEGIN marker for {name!r} not found")
    if not end_indices:
        raise ValueError(f"splice_generated: END marker for {name!r} not found")
    if len(begin_indices) > 1:
        raise ValueError(f"splice_generated: BEGIN marker for {name!r} appears more than once")
    if len(end_indices) > 1:
        raise ValueError(f"splice_generated: END marker for {name!r} appears more than once")

    begin_idx = begin_indices[0]
    end_idx = end_indices[0]
    if end_idx <= begin_idx:
        raise ValueError(f"splice_generated: END marker for {name!r} appears before BEGIN marker")

    before = lines[: begin_idx + 1]
    after = lines[end_idx:]

    # Match the BEGIN marker line's own line-ending style (falls back to no
    # trailing newline if the marker line itself had none).
    newline = "\n" if lines[begin_idx].endswith("\n") else ""

    stripped_content = content.rstrip("\n")
    middle = f"{stripped_content}{newline}" if stripped_content else ""

    return "".join(before) + middle + "".join(after)


# ---------------------------------------------------------------------------
# CSV loading + cell selection
# ---------------------------------------------------------------------------


def load_rows(path: str | pathlib.Path) -> list[dict]:
    """Load a comparison-schema CSV into a list of row dicts (NaN -> None)."""
    df = pd.read_csv(path)
    return _df_to_rows(df)


def _cell_matches(row: dict, n: int, m: int) -> bool:
    """True if row['n']/row['m'] parse to the given (n, m) (NaN-safe)."""
    try:
        return int(row.get("n")) == n and int(row.get("m")) == m
    except (TypeError, ValueError):
        return False


def select_cell(rows: list[dict], op: str, n: int, m: int) -> dict:
    """
    Select the fdars / python / r rows for one (op, n, m) headline cell.

    - "fdars": the row whose `source` equals `criterion:crosslang_{op}/n{n}_m{m}`
      — the grid-aligned fdars bench (fdars-core/benches/crosslang_grid.rs),
      NOT the pre-existing non-grid-aligned criterion ids.
    - "python": the `library == "python"` row with matching op/n/m.
    - "r": the `library == "r_svd"` row with matching op/n/m (the SVD-matched
      R FPCA comparator, not the ecosystem-realistic `r_native_pca_fd`; see
      116-CONTEXT.md).

    Any of the three may be missing (value is None) — callers render a missing
    value as an em dash and never headline an incomplete row.
    """
    fdars_source = f"criterion:crosslang_{op}/n{n}_m{m}"
    fdars_row = next((r for r in rows if r.get("source") == fdars_source), None)
    python_row = next(
        (
            r
            for r in rows
            if r.get("library") == "python" and r.get("op") == op and _cell_matches(r, n, m)
        ),
        None,
    )
    r_row = next(
        (
            r
            for r in rows
            if r.get("library") == "r_svd" and r.get("op") == op and _cell_matches(r, n, m)
        ),
        None,
    )
    return {"fdars": fdars_row, "python": python_row, "r": r_row}


# ---------------------------------------------------------------------------
# Ratio labeling
# ---------------------------------------------------------------------------


def ratio_label(fdars_ns, other_ns, band_pct: float = _PARITY_BAND_PCT) -> str:
    """
    Label the fdars-vs-other speed relationship for one headline cell.

    ratio = other_ns / fdars_ns.
      - ratio >= 1 + band/100        -> "{ratio:.2f}x faster" (fdars is faster)
      - ratio <= 1 / (1 + band/100)  -> "{fdars/other:.2f}x slower" (fdars is slower)
      - otherwise                    -> "comparable" (within the parity band)
    A missing/non-numeric/non-positive input returns an em dash.
    """
    try:
        fdars_f = float(fdars_ns)
        other_f = float(other_ns)
    except (TypeError, ValueError):
        return _EM_DASH
    if fdars_f != fdars_f or other_f != other_f:  # NaN check (NaN != NaN)
        return _EM_DASH
    if fdars_f <= 0 or other_f <= 0:
        return _EM_DASH

    band = band_pct / 100.0
    ratio = other_f / fdars_f
    if ratio >= 1.0 + band:
        return f"{ratio:.2f}{_TIMES} faster"
    if ratio <= 1.0 / (1.0 + band):
        return f"{(fdars_f / other_f):.2f}{_TIMES} slower"
    return "comparable"


# ---------------------------------------------------------------------------
# headline block emission
# ---------------------------------------------------------------------------


def emit_headline(rows: list[dict], ops: list[str], cell: tuple[int, int]) -> str:
    """
    Emit the headline markdown table: one row per op at a single (N, M) cell.

    A trailing dagger marks an fdars value whose noise_gate is not PASS
    (measurement failed the RSD/CI-width noise gate — never headlined as a
    confirmed win/loss, per D-06/D-08).
    """
    n, m = cell
    lines: list[str] = [_HEADLINE_HEADER, _HEADLINE_SEPARATOR]

    for op in ops:
        sel = select_cell(rows, op, n, m)
        fdars_row = sel["fdars"]
        python_row = sel["python"]
        r_row = sel["r"]

        fdars_ns = fdars_row.get("mean_ns") if fdars_row else None
        python_ns = python_row.get("mean_ns") if python_row else None
        r_ns = r_row.get("mean_ns") if r_row else None

        fdars_ms = _ms(float(fdars_ns)) if fdars_ns is not None else _EM_DASH
        if fdars_row is not None and fdars_row.get("noise_gate") != "PASS":
            fdars_ms = f"{fdars_ms}{_NOISE_DAGGER}"
        python_ms = _ms(float(python_ns)) if python_ns is not None else _EM_DASH
        r_ms = _ms(float(r_ns)) if r_ns is not None else _EM_DASH

        vs_python = ratio_label(fdars_ns, python_ns)
        vs_r = ratio_label(fdars_ns, r_ns)

        lines.append(f"| {op} | {n} | {m} | {fdars_ms} | {python_ms} | {r_ms} | {vs_python} | {vs_r} |")

    lines.append("")
    lines.append(
        f"{_NOISE_DAGGER} fdars measurement failed the noise gate "
        "(RSD >= 5% or CI-width >= 5%) — not headlined as significant."
    )
    lines.append("")
    lines.append("_Generated by benchmarks/render_report.py — do not edit by hand._")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Render generated performance tables into a markdown doc "
                     "from committed cross-language comparison CSVs."
    )
    parser.add_argument(
        "--after", type=str, required=True,
        help="Path to the after-run comparison CSV (e.g. benchmarks/results/comparison.csv).",
    )
    parser.add_argument(
        "--doc", type=str, required=True,
        help="Path to the markdown doc to splice generated blocks into.",
    )
    parser.add_argument(
        "--blocks", type=str, nargs="+", default=list(BLOCKS),
        help=f"Which generated blocks to render (default: all of {list(BLOCKS)}).",
    )
    args = parser.parse_args(argv)

    after_path = pathlib.Path(args.after)
    doc_path = pathlib.Path(args.doc)

    if not after_path.exists():
        print(f"ERROR: {after_path} not found", file=sys.stderr)
        return 1
    if not doc_path.exists():
        print(f"ERROR: {doc_path} not found", file=sys.stderr)
        return 1

    unknown_blocks = [b for b in args.blocks if b not in BLOCKS]
    if unknown_blocks:
        print(
            f"ERROR: unknown block(s) {unknown_blocks}; valid blocks: {list(BLOCKS)}",
            file=sys.stderr,
        )
        return 2

    rows = load_rows(after_path)
    doc_text = doc_path.read_text(encoding="utf-8")

    for block in args.blocks:
        if block == "headline":
            content = emit_headline(rows, list(CROSSLANG_OPS), HEADLINE_CELL)
        else:
            # Unreachable given the unknown_blocks check above; fail closed
            # rather than silently no-op if BLOCKS grows without a matching
            # emit_* arm in a future plan.
            print(f"ERROR: no emitter wired for block {block!r}", file=sys.stderr)
            return 2
        doc_text = splice_generated(doc_text, block, content)

    doc_path.write_text(doc_text, encoding="utf-8")
    print(f"Spliced block(s) {args.blocks} into {doc_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
