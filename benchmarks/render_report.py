# Criterion settings parsing (D-15)
# ---------------------------------------------------------------------------


def parse_criterion_settings(text: str) -> dict[str, dict]:
    """
    Parse `{group: {sample_size, measurement_time_s, warm_up_s}}` from Rust
    criterion bench source text. Accepts both `Duration::from_secs(n)` and
    `std::time::Duration::from_secs(n)`. A group with no explicit setting for
    a given knob maps that key to None.
    """
    result: dict[str, dict] = {}
    for match in _GROUP_BLOCK_RE.finditer(text):
        group = match.group(1)
        block = match.group(2)
        sample_size_m = _SAMPLE_SIZE_RE.search(block)
        measurement_m = _MEASUREMENT_TIME_RE.search(block)
        warm_up_m = _WARM_UP_RE.search(block)
        result[group] = {
            "sample_size": int(sample_size_m.group(1)) if sample_size_m else None,
            "measurement_time_s": int(measurement_m.group(1)) if measurement_m else None,
            "warm_up_s": int(warm_up_m.group(1)) if warm_up_m else None,
        }
    return result


# ---------------------------------------------------------------------------
# Markdown cell escaping (T-116-13)
# ---------------------------------------------------------------------------


def _md_cell(value) -> str:
    """
    Render one markdown table cell value safely: None/NaN -> em dash;
    pipes escaped; CR/LF collapsed to spaces (a free-text `notes` field must
    never be able to break a table row or inject an extra row).
    """
    if value is None:
        return _EM_DASH
    if isinstance(value, float) and value != value:  # NaN
        return _EM_DASH
    text = str(value)
    text = text.replace("\r\n", " ").replace("\r", " ").replace("\n", " ")
    text = text.replace("|", "\\|")
    return text


# ---------------------------------------------------------------------------
# Ratio labeling
# ---------------------------------------------------------------------------


def ratio_label(fdars_ns, other_ns, band_pct: float = _PARITY_BAND_PCT) -> str:
    """
    Label the fdars-vs-other speed relationship for one headline cell.

    ratio = other_ns / fdars_ns.
      - ratio >= 1 + band/100        -> "{ratio:.2f}x faster" (fdars is faster)
      - ratio <= 1 / (1 + band/100)  -> "{fdars/other:.2f}x slower" (fdars is slower)
      - otherwise                    -> "comparable" (within the parity band)
    A missing/non-numeric/non-positive input returns an em dash.
    """
    try:
        fdars_f = float(fdars_ns)
        other_f = float(other_ns)
    except (TypeError, ValueError):
        return _EM_DASH
    if fdars_f != fdars_f or other_f != other_f:  # NaN check (NaN != NaN)
        return _EM_DASH
    if fdars_f <= 0 or other_f <= 0:
        return _EM_DASH

    band = band_pct / 100.0
    ratio = other_f / fdars_f
    if ratio >= 1.0 + band:
        return f"{ratio:.2f}{_TIMES} faster"
    if ratio <= 1.0 / (1.0 + band):
        return f"{(fdars_f / other_f):.2f}{_TIMES} slower"
    return "comparable"


# ---------------------------------------------------------------------------
# headline block emission
# ---------------------------------------------------------------------------


def emit_headline(rows: list[dict], ops: list[str], cell: tuple[int, int]) -> str:
    """
    Emit the headline markdown table: one row per op at a single (N, M) cell.

    A trailing dagger marks an fdars value whose noise_gate is not PASS
    (measurement failed the RSD/CI-width noise gate — never headlined as a
    confirmed win/loss, per D-06/D-08).
    """
    n, m = cell
    lines: list[str] = [_HEADLINE_HEADER, _HEADLINE_SEPARATOR]

    for op in ops:
        sel = select_cell(rows, op, n, m)
        fdars_row = sel["fdars"]
        python_row = sel["python"]
        r_row = sel["r"]

        fdars_ns = fdars_row.get("mean_ns") if fdars_row else None
        python_ns = python_row.get("mean_ns") if python_row else None
        r_ns = r_row.get("mean_ns") if r_row else None

        fdars_ms = _ms(float(fdars_ns)) if fdars_ns is not None else _EM_DASH
        if fdars_row is not None and fdars_row.get("noise_gate") != "PASS":
            fdars_ms = f"{fdars_ms}{_NOISE_DAGGER}"
        python_ms = _ms(float(python_ns)) if python_ns is not None else _EM_DASH
        r_ms = _ms(float(r_ns)) if r_ns is not None else _EM_DASH

        vs_python = ratio_label(fdars_ns, python_ns)
        vs_r = ratio_label(fdars_ns, r_ns)

        lines.append(f"| {op} | {n} | {m} | {fdars_ms} | {python_ms} | {r_ms} | {vs_python} | {vs_r} |")

    lines.append("")
    lines.append(
        f"{_NOISE_DAGGER} fdars measurement failed the noise gate "
        "(RSD >= 5% or CI-width >= 5%) — not headlined as significant."
    )
    lines.append("")
    lines.append("_Generated by benchmarks/render_report.py — do not edit by hand._")
    return "\n".join(lines)


