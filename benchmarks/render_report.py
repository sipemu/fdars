def block_markers(name: str) -> tuple[str, str]:
    """Return the (BEGIN, END) marker line pair for a generated block `name`."""
    return (f"<!-- BEGIN GENERATED: {name} -->", f"<!-- END GENERATED: {name} -->")


def splice_generated(text: str, name: str, content: str) -> str:
    """
    Replace everything strictly between the BEGIN/END GENERATED marker lines
    for `name` with `content`.

    Raises ValueError if either marker is missing from `text`, or if either
    marker line appears more than once (an ambiguous splice target — the doc
    must carry exactly one marker pair per block name).

    Idempotent: splicing identical `content` into an already-spliced document
    returns the document byte-for-byte unchanged, which is what the plan's
    "re-running step 6(e) leaves `git diff --quiet` true" determinism
    requirement relies on.
    """
    begin_marker, end_marker = block_markers(name)
    lines = text.splitlines(keepends=True)

    begin_indices = [i for i, line in enumerate(lines) if line.rstrip("\n") == begin_marker]
    end_indices = [i for i, line in enumerate(lines) if line.rstrip("\n") == end_marker]

    if not begin_indices:
        raise ValueError(f"splice_generated: BEGIN marker for {name!r} not found")
    if not end_indices:
        raise ValueError(f"splice_generated: END marker for {name!r} not found")
    if len(begin_indices) > 1:
        raise ValueError(f"splice_generated: BEGIN marker for {name!r} appears more than once")
    if len(end_indices) > 1:
        raise ValueError(f"splice_generated: END marker for {name!r} appears more than once")

    begin_idx = begin_indices[0]
    end_idx = end_indices[0]
    if end_idx <= begin_idx:
        raise ValueError(f"splice_generated: END marker for {name!r} appears before BEGIN marker")

    before = lines[: begin_idx + 1]
    after = lines[end_idx:]

    # Match the BEGIN marker line's own line-ending style (falls back to no
    # trailing newline if the marker line itself had none).
    newline = "\n" if lines[begin_idx].endswith("\n") else ""

    stripped_content = content.rstrip("\n")
    middle = f"{stripped_content}{newline}" if stripped_content else ""

    return "".join(before) + middle + "".join(after)


