def emit_runtime(inputs: dict) -> str:
    log = inputs.get("rerun_log") or {}
    meta = log.get("meta", {})
    records = log.get("records", [])

    lines = [
        _notice(["rerun_log.json"]),
        "",
        f"head_sha: `{meta.get('head_sha', _EM_DASH)}`  \nstarted_utc: `{meta.get('started_utc', _EM_DASH)}`",
        "",
        "| Kind | Status | Count | Wall-clock (s) |",
        "|---|---|---|---|",
    ]
    agg: dict[tuple, list] = {}
    total_wall = 0.0
    for rec in records:
        key = (rec.get("kind"), rec.get("status"))
        wall = rec.get("wall_s") or 0.0
        bucket = agg.setdefault(key, [0, 0.0])
        bucket[0] += 1
        bucket[1] += wall
        total_wall += wall
    for (kind, status), (count, wall) in sorted(agg.items(), key=lambda kv: (str(kv[0][0]), str(kv[0][1]))):
        lines.append(f"| {kind} | {status} | {count} | {wall:.1f} |")

    lines.append("")
    lines.append(f"Total measured wall-clock: {total_wall / 3600.0:.2f} hours")

    footprint = next((rec for rec in reversed(records) if rec.get("kind") == "footprint"), None)
    if footprint is not None:
        gib = footprint.get("target_bytes", 0) / (1024**3)
        lines.append(f"Disk footprint (target/): {gib:.2f} GiB")

    return "\n".join(lines)


