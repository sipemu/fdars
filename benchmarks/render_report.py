def render_blocks(inputs: dict, names: list[str]) -> dict[str, str]:
    """
    Render the requested generated blocks from `inputs`.

    Fails closed (ValueError, naming the missing file) when a requested
    block's required input key is absent (None) from `inputs` — main()
    turns this into stderr + exit 1, never a partial/silent doc write.
    """
    rendered: dict[str, str] = {}
    for name in names:
        if name not in REQUIRED_INPUTS:
            raise ValueError(f"render_blocks: unknown block {name!r}; valid blocks: {list(BLOCKS)}")
        missing = [key for key in REQUIRED_INPUTS[name] if inputs.get(key) is None]
        if missing:
            missing_paths = [str(inputs.get(f"{key}_path", key)) for key in missing]
            raise ValueError(
                f"render_blocks: block {name!r} requires {missing} which is missing "
                f"(expected at {missing_paths})"
            )
        rendered[name] = _EMITTERS[name](inputs)
    return rendered


def update_docs(doc_paths: list[str], rendered: dict[str, str], write: bool = True) -> list[str]:
    """
    Splice every block in `rendered` into every doc in `doc_paths` that
    carries its marker pair. Returns the list of block names whose spliced
    content differs from what was on disk (the --check "stale" list).

    Raises ValueError if a requested block's markers exist in NONE of the
    docs. Never writes when `write=False` (main --check's contract).
    """
    original_texts = {path: pathlib.Path(path).read_text(encoding="utf-8") for path in doc_paths}
    updated_texts = dict(original_texts)
    stale: list[str] = []

    for name, content in rendered.items():
        begin, end = block_markers(name)
        found_any = False
        for path in doc_paths:
            text = updated_texts[path]
            if begin in text and end in text:
                found_any = True
                new_text = splice_generated(text, name, content)
                if new_text != original_texts[path] and name not in stale:
                    stale.append(name)
                updated_texts[path] = new_text
        if not found_any:
            raise ValueError(f"update_docs: no marker pair for block {name!r} found in any of {doc_paths}")

    if write:
        for path in doc_paths:
            if updated_texts[path] != original_texts[path]:
                pathlib.Path(path).write_text(updated_texts[path], encoding="utf-8")

    return stale


# ---------------------------------------------------------------------------
# check-prose (prose numbers must be backed by a generated block)
# ---------------------------------------------------------------------------

_MARKER_BLOCK_RE = re.compile(
    r"<!-- BEGIN GENERATED: ([\w-]+) -->\n(.*?)<!-- END GENERATED: \1 -->", re.DOTALL
)
_NUMBER_UNIT_RE = re.compile(r"(\d[\d,]*\.?\d*)\s*(?:×|[xX]\s|ms\b)")


def _extract_generated_text(doc_text: str) -> str:
    return "\n".join(match.group(2) for match in _MARKER_BLOCK_RE.finditer(doc_text))


def _strip_generated_blocks(text: str) -> str:
    return _MARKER_BLOCK_RE.sub("", text)


def _extract_readme_performance_section(readme_text: str) -> str:
    match = re.search(r"^## Performance\b(.*?)(?=^## |\Z)", readme_text, re.DOTALL | re.MULTILINE)
    return match.group(1) if match else ""


def check_prose(doc_text: str, readme_text: str) -> list[str]:
    """
    Return every number-with-unit (`<num>×` or `<num> ms`) found in the
    hand-written prose of `doc_text` (outside its own generated blocks) or in
    the README's "## Performance" section prose, that does NOT appear
    verbatim inside any of `doc_text`'s generated blocks.

    This is the "prose can only quote numbers that exist in generated
    tables" guard: it never inspects README-local generated blocks (the
    README's own headline snippet), only PERFORMANCE.md's, since
    PERFORMANCE.md is the source of truth every generated number lives in.
    """
    generated_text = _extract_generated_text(doc_text)
    prose_sections = [
        _strip_generated_blocks(doc_text),
        _strip_generated_blocks(_extract_readme_performance_section(readme_text)),
    ]

    offenders: list[str] = []
    seen = set()
    for prose in prose_sections:
        for match in _NUMBER_UNIT_RE.finditer(prose):
            number = match.group(1)
            if number not in generated_text and number not in seen:
                seen.add(number)
                offenders.append(number)
    return offenders


