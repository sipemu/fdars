def _load_inputs_from_paths(paths: dict) -> dict:
    """Build the `inputs` dict from a plain {key: path-string} mapping."""
    inputs: dict = {}

    def _maybe_csv(key: str) -> None:
        path = pathlib.Path(paths[key])
        inputs[f"{key}_path"] = path
        inputs[key] = load_rows(path) if path.exists() else None

    def _maybe_json(key: str) -> None:
        path = pathlib.Path(paths[key])
        inputs[f"{key}_path"] = path
        if path.exists():
            with open(path, encoding="utf-8") as f:
                inputs[key] = json.load(f)
        else:
            inputs[key] = None

    _maybe_csv("baseline")
    _maybe_csv("after")
    _maybe_json("env")
    _maybe_json("env_baseline")
    _maybe_json("rerun_log")
    _maybe_json("ab_manifest")

    bench_dir = pathlib.Path(paths["bench_dir"])
    inputs["bench_dir_path"] = bench_dir
    inputs["bench_dir"] = bench_dir if bench_dir.exists() else None

    return inputs


def _load_inputs(args: argparse.Namespace) -> dict:
    return _load_inputs_from_paths({
        "baseline": args.baseline,
        "after": args.after,
        "env": args.env,
        "env_baseline": args.env_baseline,
        "rerun_log": args.rerun_log,
        "ab_manifest": args.ab_manifest,
        "bench_dir": args.bench_dir,
    })


