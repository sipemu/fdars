# ------------------------------------------------------ two-step GFPCA ----
twostep_case <- function(prefix, seed, n, m, fam_code, family, npc = 2, Kt = 8) {
  Y <- sim(seed, n, m, fam_code); Y$t <- NULL
  emit_scalar(paste0(prefix, "_DATA_SUM"), sum(Y$value))
  # cov_hall exactly as called inside gfpca_twoStep
  Yc <- Y
  if (family == "poisson") Yc$value <- round(Yc$value)
  Yc$index <- registr:::coarsen_index(Yc$index, 4L)
  grid <- sort(unique(Yc$index))
  cv <- registr:::cov_hall(Yc, index_evalGrid = grid, Kt = Kt, family = family, diag_epsilon = 0.01)
  emit(paste0(prefix, "_GRID"), grid)
  idx <- seq(1, length(grid), by = 3)   # every third grid point keeps the file small
  emit(paste0(prefix, "_COV_SUB"), cv[idx, idx])
  fit <- gfpca_twoStep(Y, family = family, npc = npc, Kt = Kt, verbose = 0)
  emit(paste0(prefix, "_ALPHA"), fit$alpha)
  emit(paste0(prefix, "_EFUN"), fit$efunctions)
  emit(paste0(prefix, "_EVAL"), fit$evalues)
  emit_scalar(paste0(prefix, "_EVAL_SUM"), fit$evalues_sum)
  emit(paste0(prefix, "_SCORES"), fit$scores)   # n x npc column-major
  emit(paste0(prefix, "_THETA"), fit$gamm4_theta)
}
