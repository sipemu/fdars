# ----------------------------------------- register_fpca(two-step) e2e ----
for (case in list(list("RG", 101, 15, 30, 0, "gaussian"), list("RB", 202, 40, 30, 1, "binomial"),
                  list("RP", 303, 20, 30, 2, "poisson"))) {
  Y <- sim(case[[2]], case[[3]], case[[4]], case[[5]]); Y$t <- NULL
  # 3 significant digits: a common grid of <= 101 rounded registered times keeps
  # the covariance small (fdars' tests run unoptimised).
  rf <- register_fpca(Y, family = case[[6]], npc = 2, Kt = 8, Kh = 4, fpca_type = "two-step",
                      fpca_index_significantDigits = 3L, verbose = 0)
  emit(paste0(case[[1]], "_BETA"), rf$hinv_beta)
  emit(paste0(case[[1]], "_REGLOSS"), rf$convergence$registration_loss)
  emit_usize(paste0(case[[1]], "_ITER"), rf$convergence$iterations)
  emit(paste0(case[[1]], "_ALPHA"), rf$fpca_obj$alpha)
  emit(paste0(case[[1]], "_TVEC"), rf$fpca_obj$t_vec)
  emit(paste0(case[[1]], "_EFUN"), rf$fpca_obj$efunctions)
  emit(paste0(case[[1]], "_EVAL"), rf$fpca_obj$evalues)
}

