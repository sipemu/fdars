# Golden values for fdars-core `pairwise_synchronization` (ALN-WFDA, GH #61).
#
# Reference: R fdapace 0.6.0 `WFDA(Ly, Lt, optns)` (minqa 1.2.x bobyqa optimiser).
# Run: Rscript golden_wfda.R   (fdapace installed into ~/.cache/R-lib)
#
# subsetProp = 1 makes the candidate set "all other curves", so the result does
# not depend on R's RNG (sample() only permutes the candidates; the truncated /
# weighted averages are order-invariant).
#
# `WFDA_fixed` is a copy of fdapace's WFDA with ONE line changed: fdapace 0.6.0
# computes the pairwise cost as
#   mean((getcurveJ(tj = hik, curvei) - ymatNormalised[candidateKcurves[k]])^2)
# i.e. against a single matrix *element* (linear index), not curve k. The fixed
# copy uses the pairwise data-fit term mean((y_k(h_ik(t)) - y_i(t))^2), which is
# fdars' default `WfdaCostMeasure::PairwiseFit`; the unmodified WFDA backs
# `WfdaCostMeasure::FdapaceLegacy`.
.libPaths(c("~/.cache/R-lib", .libPaths()))
suppressMessages(library(fdapace))
cat("//! Golden values from R fdapace ", as.character(packageVersion("fdapace")),
    " (minqa ", as.character(packageVersion("minqa")), " BOBYQA) `WFDA`.\n//!\n",
    "//! Generated by `.planning/quick/261126-al4-aln-wfda-tang-mueller-pairwise-synchroni/golden_wfda.R`;\n",
    "//! do not edit. Data: N = 8, M = 41, t = seq(0, 10, len = 41), subsetProp = 1.\n",
    "//! Matrices are column-major N x M; warps on fdapace's [0, 1] work scale.\n", sep = "")

set.seed(1)  # WFDA saves/restores .Random.seed, which must exist
N <- 8; M <- 41
tt <- seq(0, 10, length.out = M)
u <- (tt - 0) / 10
f <- function(s) 1.5 * exp(-((s - 0.3) / 0.08)^2) + exp(-((s - 0.7) / 0.1)^2) + 0.2
a <- c(-0.5, -0.3, -0.1, 0.0, 0.15, 0.3, 0.45, 0.6) * 0.8
amp <- c(1.0, 1.2, 0.9, 1.1, 0.8, 1.3, 1.05, 0.95)
Y <- t(sapply(1:N, function(i) amp[i] * f(u + a[i] * u * (1 - u))))
Ly <- lapply(1:N, function(i) Y[i, ]); Lt <- lapply(1:N, function(i) tt)

src <- deparse(fdapace::WFDA, width.cutoff = 500L)
line <- grep("distMat\\[i, k\\] =", src)
stopifnot(length(line) == 1)
src[line] <- "distMat[i, k] = mean((getcurveJ(tj = hikMat[k, , i], ymatNormalised[candidateKcurves[k], ]) - curvei)^2)"
WFDA_fixed <- eval(parse(text = src))
environment(WFDA_fixed) <- asNamespace("fdapace")
cat("//! FIX_* = WFDA with the pairwise-cost line patched to:\n//! `", src[line], "`\n\n",
    "#![allow(clippy::unreadable_literal, clippy::excessive_precision)]\n\n", sep = "")

emit <- function(name, x) {
  cat(sprintf("pub(super) const %s: [f64; %d] = [\n", name, length(x)))
  v <- sprintf("%.15e,", x)
  rows <- split(v, ceiling(seq_along(v) / 4))
  cat(paste0("    ", vapply(rows, paste, "", collapse = " "), collapse = "\n"), "\n];\n")
}
emit_mat <- function(name, X) emit(name, as.vector(X))  # column-major (n x m)

emit("Y_DATA", as.vector(Y))
run <- function(tag, fun, optns) {
  r <- fun(Ly, Lt, optns)
  cat(sprintf("pub(super) const %s_LAMBDA: f64 = %.15e;\n", tag, r$lambda))
  emit_mat(paste0(tag, "_H"), r$h)
  if (tag %in% c("LEG_TRUNC", "FIX_TRUNC")) emit_mat(paste0(tag, "_HINV"), r$hInv)
  emit_mat(paste0(tag, "_ALIGNED"), r$aligned)
  emit(paste0(tag, "_COSTS"), r$costs)
}
run("LEG_TRUNC", WFDA, list(subsetProp = 1, choice = "truncated"))
run("LEG_WEIGHT", WFDA, list(subsetProp = 1, choice = "weighted"))
run("FIX_TRUNC", WFDA_fixed, list(subsetProp = 1, choice = "truncated"))
run("FIX_WEIGHT", WFDA_fixed, list(subsetProp = 1, choice = "weighted"))
run("FIX_K3_L", WFDA_fixed, list(subsetProp = 1, choice = "truncated", nknots = 3, lambda = 1e-3))
