def f(v):
    v = float(v)
    if np.isinf(v):
        return "f64::INFINITY" if v > 0 else "f64::NEG_INFINITY"
    if np.isnan(v):
        return "f64::NAN"
    r = repr(v)
    return r if ("." in r or "e" in r) else r + ".0"


def arr(a):
    return "&[" + ", ".join(f(v) for v in np.ravel(a)) + "]"


def lcss_path_terminates(x, y, eps, kw):
    bm = create_bounding_matrix(len(x), len(y), kw.get("window"), kw.get("itakura_max_slope"))
    cm = D.lcss_cost_matrix(x, y, epsilon=eps, **kw)
    i, j = len(x), len(y)
    while i > 0 and j > 0:
        if not bm[i - 1, j - 1]:
            return False
        if abs(x[i - 1] - y[j - 1]) <= eps:
            i, j = i - 1, j - 1
        elif cm[i - 1, j] > cm[i, j - 1]:
            i -= 1
        else:
            j -= 1
    return True


