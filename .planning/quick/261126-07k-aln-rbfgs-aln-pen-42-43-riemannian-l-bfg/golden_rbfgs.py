"""Golden values for ALN-RBFGS (#42): fdasrsf 2.7.5 optimum_reparam(method="RBFGS").

Run with ~/.cache/fdars-golden-venv/bin/python golden_rbfgs.py
SRSFs are given analytically so the Rust tests reproduce them exactly.
"""
import numpy as np
import fdasrsf
from fdasrsf.utility_functions import optimum_reparam

print("fdasrsf", fdasrsf.__version__ if hasattr(fdasrsf, "__version__") else "2.7.5")
np.set_printoptions(precision=17)


def bump(t, c, s):
    return np.exp(-((t - c) ** 2) / s)


def case_a(m):
    t = np.linspace(0, 1, m)
    q1 = 3 * bump(t, 0.35, 0.01) - 2 * bump(t, 0.7, 0.01) + 0.2
    q2 = 3 * bump(t, 0.45, 0.01) - 2 * bump(t, 0.78, 0.01) + 0.2
    return t, q1, q2


def case_b(m):
    t = np.linspace(0, 1, m)
    q1 = np.sin(4 * np.pi * t) + 0.5
    q2 = np.sin(4 * np.pi * t ** 1.3) + 0.5
    return t, q1, q2


for name, fn, m in [("A41", case_a, 41), ("B41", case_b, 41), ("A101", case_a, 101)]:
    t, q1, q2 = fn(m)
    for pen, lam in [("roughness", 0.0), ("l2psi", 0.0)][:1]:
        gam = optimum_reparam(q1, t, q2, method="RBFGS", lam=lam, penalty=pen)
        print(f"// {name} RBFGS lam={lam}")
        print("[" + ", ".join(f"{g:.12e}" for g in gam) + "]")
    gdp = optimum_reparam(q1, t, q2, method="DP")
    print(f"// {name} DP")
    print("[" + ", ".join(f"{g:.12e}" for g in gdp) + "]")


def emit_rust(path):
    out = ["// Generated by golden_rbfgs.py — fdasrsf 2.7.5,",
           "// optimum_reparam(q1, t, q2, method=..., lam=0.0) on t = linspace(0, 1, m).",
           ""]
    for name, fn, m in [("A41", case_a, 41), ("B41", case_b, 41), ("A101", case_a, 101)]:
        t, q1, q2 = fn(m)
        for meth in ["RBFGS", "DP"]:
            gam = optimum_reparam(q1, t, q2, method=meth)
            out.append(f"pub(super) const FDASRSF_{meth}_{name}: [f64; {m}] = [")
            out.append(", ".join(repr(float(g)) for g in gam) + ",")
            out.append("];")
    open(path, "w").write("\n".join(out) + "\n")


import sys
if len(sys.argv) > 1:
    emit_rust(sys.argv[1])
