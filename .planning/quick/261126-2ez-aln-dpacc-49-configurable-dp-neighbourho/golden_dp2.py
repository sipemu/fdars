"""Golden values for ALN-DPACC (#49): fdasrsf 2.7.5 optimum_reparam(method="DP2", grid_dim=...).

Run with ~/.cache/fdars-golden-venv/bin/python golden_dp2.py <out.rs>
SRSFs are given analytically (same cases as golden_rbfgs.py) so the Rust tests
reproduce them exactly.
"""
import sys
import numpy as np
from fdasrsf.utility_functions import optimum_reparam


def bump(t, c, s):
    return np.exp(-((t - c) ** 2) / s)


def case_a(m):
    t = np.linspace(0, 1, m)
    q1 = 3 * bump(t, 0.35, 0.01) - 2 * bump(t, 0.7, 0.01) + 0.2
    q2 = 3 * bump(t, 0.45, 0.01) - 2 * bump(t, 0.78, 0.01) + 0.2
    return t, q1, q2


def case_b(m):
    t = np.linspace(0, 1, m)
    q1 = np.sin(4 * np.pi * t) + 0.5
    q2 = np.sin(4 * np.pi * t ** 1.3) + 0.5
    return t, q1, q2


CASES = [
    ("A41_G10", case_a, 41, 10, "none", 0.0),
    ("B41_G10", case_b, 41, 10, "none", 0.0),
    ("A101_G10", case_a, 101, 10, "none", 0.0),
    ("B61_G7", case_b, 61, 7, "none", 0.0),
    ("A61_G10_L2GAM", case_a, 61, 10, "l2gam", 0.05),
]

out = ["// Generated by golden_dp2.py — fdasrsf 2.7.5,",
       "// optimum_reparam(q1, t, q2, method=\"DP2\", grid_dim=G, penalty=P, lam=L)",
       "// on t = linspace(0, 1, m) (case_a / case_b of optim_tests.rs).",
       ""]
for name, fn, m, g, pen, lam in CASES:
    t, q1, q2 = fn(m)
    gam = optimum_reparam(q1, t, q2, method="DP2", grid_dim=g, penalty=pen, lam=lam)
    out.append(f"// grid_dim={g} penalty={pen} lam={lam}")
    out.append(f"pub(super) const FDASRSF_DP2_{name}: [f64; {m}] = [")
    out.append(", ".join(repr(float(x)) for x in gam) + ",")
    out.append("];")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print("ok")
